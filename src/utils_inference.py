def evaluate_classification_results(experiments, exp_num, index_to_clusters, save_path='confusion_matrix.pdf'):
    """
    Evaluates an experiment by generating the confusion matrix, accuracy, and classification report.
    
    Parameters:
    - experiments: The object containing the experiment data.
    - exp_num: The experiment number to evaluate.
    - index_to_clusters: A dictionary mapping numerical labels to string labels.
    - save_path: Path to save the confusion matrix plot (default: 'confusion_matrix.pdf').

    Returns:
    - accuracy: Accuracy score of the model.
    - class_report: Classification report as a string.
    - conf_matrix: The confusion matrix as a NumPy array.
    """
    
    # Initialize lists to store the true and predicted classes
    true_classes = []
    pred_classes = []
    
    # Iterate over each item in the experiment's model
    for i in range(len(experiments.experiments[exp_num].model['class_score'])):
        # Calculate the predicted class using softmax and argmax
        predicted_class = np.argmax(softmax(experiments.experiments[exp_num].model['class_score'][i]))
        # Get the actual class label
        true_class = np.argmax(experiments.experiments[exp_num].model['class_labels'][i])
        
        # Append the true and predicted classes to their respective lists
        true_classes.append(true_class)
        pred_classes.append(predicted_class)

    # Convert numerical labels to string labels
    true_classes_str = [index_to_clusters[cls] for cls in true_classes]
    pred_classes_str = [index_to_clusters[cls] for cls in pred_classes]

    # Print the experiment number
    print(f"Experiment Number: {exp_num}")

    # Generate the confusion matrix
    conf_matrix = confusion_matrix(true_classes_str, pred_classes_str, labels=list(index_to_clusters.values()))

    # Print the confusion matrix
    print("\nConfusion Matrix:")
    print(conf_matrix)

    # Calculate accuracy and classification report
    accuracy = accuracy_score(true_classes_str, pred_classes_str)
    class_report = classification_report(true_classes_str, pred_classes_str)

    print("\nClassification Report:")
    print(class_report)
    print(f"Accuracy: {accuracy:.4f}")

    # Visualize the confusion matrix
    plt.figure(figsize=(10, 7))
    sns.heatmap(conf_matrix, annot=True, fmt="d", cmap="Blues",
                xticklabels=list(index_to_clusters.values()),
                yticklabels=list(index_to_clusters.values()))
    plt.xlabel('Predicted Cell Type')
    plt.ylabel('True Cell Type')
    plt.title('Confusion Matrix')
    plt.savefig(save_path, format='pdf', bbox_inches='tight')
    plt.show()

    return accuracy, class_report, conf_matrix

def plot_loss_curves(train_loss, val_loss):
    loss_categories = 7  
    plot_names = [
        '(a) Combined Loss', '(b) Reconstruction Loss', '(c) SINDy_x Loss',
        '(d) SINDy_z Loss', '(e) SINDy Norm', '(f) Autoencoder Norm', '(g) Classification Error'
    ]
    
    epochs = len(train_loss)
    x_values = np.arange(epochs) * 50  

    for i in range(loss_categories):
        # Skip 'Autoencoder Norm'
        if plot_names[i] == '(f) Autoencoder Norm':
            continue  

        plt.figure(figsize=(8, 6))
        plt.plot(x_values, train_loss[:, i], label='Training Loss')
        plt.plot(x_values, val_loss[:, i], label='Validation Loss', linestyle='--')
        plt.xlabel('Epochs')
        plt.ylabel('Loss (log scale)')
        plt.title(plot_names[i])
