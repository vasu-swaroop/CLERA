def extract_and_save_weights(experiment, model_type, num_layers, save_path):
    """
    Extracts and saves weights and biases for a given model type.

    Args:
        experiment (object): The experiment containing the model.
        model_type (str): The type of model ('decoder' or 'classifier').
        num_layers (int): Number of layers to extract.
        save_path (str): Path to save the extracted weights.
    """
    weights = {}
    biases = {}

    for layer in range(num_layers + 1):
        weights[layer] = experiment.model[f'{model_type}_weights'][layer]
        biases[layer] = experiment.model[f'{model_type}_biases'][layer]

    weights_list = [weights[layer] for layer in range(num_layers + 1)]
    biases_list = [biases[layer] for layer in range(num_layers + 1)]

    # Save the extracted weights and biases
    with open(os.path.join(save_path, f'{model_type}_weights_list.pkl'), 'wb') as f:
        pickle.dump(weights_list, f)

    with open(os.path.join(save_path, f'{model_type}_biases_list.pkl'), 'wb') as f:
        pickle.dump(biases_list, f)