def build_equations(coeff_matrix, resulting_library, coeff_thresh, active_terms):
    """
    Build equations based on coefficient matrix and library.

    This function constructs equations for each row of the coefficient matrix using the provided library and coefficient matrix.

    Arguments:
        coeff_matrix (numpy.ndarray): The coefficient matrix from the SINDy model.
        resulting_library (dict): The resulting library of equations generated by `sindy_library_equations`.
        coeff_thresh (float): The threshold below which coefficients are considered negligible.

    Returns:
        equations (list): A list of equations representing the relationships between variables.
    """
    latent_dim = coeff_matrix.shape[0]  # Number of latent dimensions

    # Check if the dimensions match
    if coeff_matrix.shape[1] != len(resulting_library):
        print('error: coeff_matrix.shape[1] != len(resulting_library)')

    equations = []
    active_variable={}
    # Iterate through each row of the coefficient matrix
    for row_index in range(0, latent_dim):
        equation_parts=[]
        active_variable[row_index] = set()
        for col_index, value in resulting_library.items():
            if np.abs(coeff_matrix[row_index][col_index]) > coeff_thresh:
                equation_parts.append(f"{coeff_matrix[row_index][col_index]:.5f}*{value}")
                active_variable[row_index].update(list(active_terms[col_index]))
        # Combine equation parts and create the equation
        equation = f"dz{row_index} = " + ' + '.join(equation_parts)
        equations.append(equation)
    return equations, active_variable


def generate_library_and_nature(params):
    """
    Generates the SINDy library and nature vector based on the parameters.

    Parameters:
    - params: Dictionary containing experiment parameters.

    Returns:
    - resulting_library: Library equations.
    - terms: List of terms.
    - tupple: Tuple containing the library information.
    - nature: List of nature signs for each term.
    """
    
    latent_dim = params['latent_dim']
    
    # Create variable library names
    variable_lib = [f'z{z}' for z in range(latent_dim)]

    # Build the SINDy library
    resulting_library, terms, tupple = sindy_library_equations(
        variable_lib, latent_dim, params['poly_order'],
        include_constant=True,
        include_sine=params['include_sine'],
        include_tan=params['include_tan'],
        include_log=params['include_log'],
        include_exp=params['include_exp'],
        include_reciprocal=params['include_reciprocal_func']
    )

    # Build the nature array
    nature = [0]  # Constant term
    nature.extend([1] * latent_dim)  # Linear terms

    # Include additional terms based on parameters
    if params['include_reciprocal_func']:
        nature.extend([-1] * latent_dim)
    if params['include_tan']:
        nature.extend([1] * latent_dim)
    if params['include_exp']:
        nature.extend([1] * latent_dim)
    nature.extend([1] * int(latent_dim * (latent_dim + 1) / 2))  # Quadratic terms
    if params['include_sine']:
        nature.extend([1] * latent_dim)

    return resulting_library, terms, tupple, nature


def evaluate_model_with_library(experiments, exp_number, params):
    """
    Evaluates the model by identifying misclassifications, building equations, and printing results.

    Parameters:
    - experiments: Object containing experiment data.
    - exp_number: Experiment index to evaluate.
    - params: Dictionary containing SINDy parameters.
    - build_equations: Function to generate the equations.

    Returns:
    - cross_index: List of misclassified indices.
    - active_terms: List of active terms in the model.
    - equations: List of generated equations.
    """
    
    print(f"\nEvaluating Experiment {exp_number}")
    
    # Generate the library and nature array
    resulting_library, terms, _, nature = generate_library_and_nature(params)

    # Identify misclassifications
    cross_index = []
    count = 0

    for i in range(len(experiments.experiments[exp_number].model['class_score'])):
        pred = np.argmax(softmax(experiments.experiments[exp_number].model['class_score'][i]))
        true = np.argmax(experiments.experiments[exp_number].model['class_labels'][i])
        
        if pred != true:
            cross_index.append(i)
            count += 1

    print(f"Misclassified samples: {count}")

    # Retrieve the coefficient matrix and build the equations
    common = (experiments.experiments[exp_number].model['coefficient_mask'] * 
              experiments.experiments[exp_number].model['sindy_coefficients']).T

    equations, active_terms = build_equations(common, resulting_library, 0, terms)

    # Apply sign correction based on nature matrix
    nature_all = [nature] * params['latent_dim']
    signum_array = np.sign(common) * nature_all

    # Display the results
    print("\nActive Terms:\n LHS terms :RHS terms")
    print(active_terms)
    
    for i, equation in enumerate(equations):
        print(f"\nEquation {i}: {equation}")

    return cross_index, active_terms, equations

